-- Notifications par email au client, à chaque changement de statut de sa souscription (ADR-0021).
-- Modèle « outbox » : la notification est enregistrée dans la même transaction que le changement de
-- statut, puis envoyée par une tâche planifiée, avec de nouvelles tentatives en cas d'échec. Aucune
-- notification n'est perdue si l'application s'arrête ou si le serveur de messagerie est indisponible.
create table notification_outbox (
    id              bigint generated by default as identity primary key,
    subscription_id bigint        not null,
    transition      varchar(20)   not null,
    recipient       varchar(255)  not null,
    reason          varchar(500),
    status          varchar(20)   not null,
    attempts        integer       not null default 0,
    -- Prochaine tentative ; sert aussi de bail pendant un envoi, pour qu'une seconde instance ne
    -- reprenne pas une notification en cours d'envoi
    next_attempt_at timestamptz   not null,
    last_error      varchar(1000),
    created_at      timestamptz   not null,
    sent_at         timestamptz,
    constraint fk_notification_subscription foreign key (subscription_id) references subscription (id),
    constraint ck_notification_transition check (transition in ('ACTIVATE', 'SUSPEND', 'REACTIVATE', 'TERMINATE')),
    constraint ck_notification_status check (status in ('PENDING', 'SENT', 'FAILED')),
    constraint ck_notification_attempts check (attempts >= 0)
);

-- Notifications à envoyer, par date de prochaine tentative : seules les lignes en attente sont indexées
create index ix_notification_due on notification_outbox (next_attempt_at) where status = 'PENDING';

-- Notifications d'une souscription (GET /api/subscriptions/{id}/notifications)
create index ix_notification_subscription on notification_outbox (subscription_id);
