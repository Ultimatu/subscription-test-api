-- Journal d'audit (ADR-0024) : une ligne par action métier, en ajout seul, écrite dans la transaction
-- de l'action. Aucune clé étrangère : le journal doit survivre aux suppressions. client_id rattache
-- un événement au client concerné, pour l'effacer avec lui lors d'une purge (loi n° 2013-450, art. 36).
create table audit_event (
    id            bigint generated by default as identity primary key,
    occurred_at   timestamptz  not null,
    actor         varchar(100) not null,
    action        varchar(40)  not null,
    resource_type varchar(20)  not null,
    resource_id   varchar(50),
    client_id     bigint,
    summary       varchar(255) not null,
    details       jsonb,
    request_id    varchar(64)
);

-- Lecture du journal, du plus récent au plus ancien
create index ix_audit_event_occurred_at on audit_event (occurred_at desc);

-- Événements d'une ressource (GET /api/audit-events?resourceType=…&resourceId=…)
create index ix_audit_event_resource on audit_event (resource_type, resource_id);

-- Effacement des événements d'un client lors de sa purge
create index ix_audit_event_client on audit_event (client_id);
