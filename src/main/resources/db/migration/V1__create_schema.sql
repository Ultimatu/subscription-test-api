create table client (
    id                  bigint generated by default as identity primary key,
    first_name          varchar(100) not null,
    last_name           varchar(100) not null,
    email               varchar(255) not null,
    phone_number_client varchar(10)  not null,
    city                varchar(100) not null,
    status              varchar(20)  not null,
    version             bigint       not null,
    created_at          timestamptz  not null,
    updated_at          timestamptz  not null,
    created_by          varchar(100) not null,
    updated_by          varchar(100) not null,
    constraint ck_client_phone_number check (phone_number_client ~ '^0[157][0-9]{8}$'),
    constraint ck_client_status check (status in ('ACTIVE', 'INACTIVE'))
);

create unique index uk_client_email on client (lower(email));
create index ix_client_city on client (city);

create table offer (
    id            bigint generated by default as identity primary key,
    code          varchar(50)    not null,
    label         varchar(255)   not null,
    technology    varchar(20)    not null,
    monthly_price numeric(12, 2) not null,
    active        boolean        not null,
    version       bigint         not null,
    created_at    timestamptz    not null,
    updated_at    timestamptz    not null,
    created_by    varchar(100)   not null,
    updated_by    varchar(100)   not null,
    constraint uk_offer_code unique (code),
    constraint ck_offer_code_uppercase check (code = upper(code)),
    constraint ck_offer_technology check (technology in ('FTTH', 'SATELLITE', '4G_BOX')),
    constraint ck_offer_monthly_price check (monthly_price > 0)
);

create index ix_offer_technology on offer (technology);

create table subscription (
    id         bigint generated by default as identity primary key,
    reference  varchar(20)  not null,
    nd         varchar(10)  not null,
    client_id  bigint       not null,
    offer_id   bigint       not null,
    status     varchar(20)  not null,
    start_date date         not null,
    end_date   date,
    version    bigint       not null,
    created_at timestamptz  not null,
    updated_at timestamptz  not null,
    created_by varchar(100) not null,
    updated_by varchar(100) not null,
    constraint uk_subscription_reference unique (reference),
    constraint uk_subscription_nd unique (nd),
    constraint fk_subscription_client foreign key (client_id) references client (id),
    constraint fk_subscription_offer foreign key (offer_id) references offer (id),
    constraint ck_subscription_reference check (reference ~ '^SUB-[0-9]{4}-[0-9]{6}$'),
    constraint ck_subscription_nd check (nd ~ '^27[0-9]{8}$'),
    constraint ck_subscription_status check (status in ('PENDING', 'ACTIVE', 'SUSPENDED', 'TERMINATED'))
);

create index ix_subscription_client on subscription (client_id);
create index ix_subscription_offer on subscription (offer_id);
create index ix_subscription_status on subscription (status);

create table subscription_status_history (
    id              bigint generated by default as identity primary key,
    subscription_id bigint       not null,
    from_status     varchar(20),
    to_status       varchar(20)  not null,
    reason          varchar(500),
    changed_at      timestamptz  not null,
    changed_by      varchar(100) not null,
    constraint fk_status_history_subscription foreign key (subscription_id) references subscription (id) on delete cascade,
    constraint ck_status_history_from_status check (from_status in ('PENDING', 'ACTIVE', 'SUSPENDED', 'TERMINATED')),
    constraint ck_status_history_to_status check (to_status in ('PENDING', 'ACTIVE', 'SUSPENDED', 'TERMINATED'))
);

create index ix_status_history_subscription on subscription_status_history (subscription_id);
