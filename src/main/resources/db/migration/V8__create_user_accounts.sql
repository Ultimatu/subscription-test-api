-- Comptes des utilisateurs de l'API (ADR-0013) : conseillers et administrateurs du back-office.
-- Le mot de passe n'est jamais stocké en clair : seule son empreinte BCrypt l'est.
create table app_user (
    id            bigint generated by default as identity primary key,
    username      varchar(50)  not null,
    password_hash varchar(100) not null,
    role          varchar(20)  not null,
    enabled       boolean      not null,
    version       bigint       not null,
    created_at    timestamptz  not null,
    updated_at    timestamptz  not null,
    created_by    varchar(100) not null,
    updated_by    varchar(100) not null,
    constraint uk_app_user_username unique (username),
    constraint ck_app_user_role check (role in ('ADMIN', 'CONSEILLER'))
);

